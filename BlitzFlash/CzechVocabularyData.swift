import Foundation

struct CzechVocabularyEntry: Hashable {
    var term: String
    var sentence: String
    var pronunciation: String
}

enum CzechVocabularyData {
    static let entries: [String: CzechVocabularyEntry] = {
        var map: [String: CzechVocabularyEntry] = [:]
        for (english, term) in terms {
            map[english] = CzechVocabularyEntry(
                term: term,
                sentence: "Slovo \(term) se objevuje v praxi.",
                pronunciation: pronunciation(for: term)
            )
        }
        return map
    }()

    static func entry(for word: VocabularyWord) -> CzechVocabularyEntry? {
        entries[word.english]
    }

    /// Çekçe terimi Türkçe harflerle yaklaşık okunuşa çevirir.
    /// Çekçe büyük ölçüde fonetik olduğu için kural tabanlı çeviri yeterli bir telaffuz rehberi verir.
    static func pronunciation(for term: String) -> String {
        var result = term.lowercased()
        // Sıra önemli: önce digraf "ch", sonra ünlü y/í, ardından ünsüzler.
        let rules: [(String, String)] = [
            ("ch", "h"),
            ("ý", "i"), ("í", "i"), ("y", "i"),
            ("á", "a"), ("é", "e"), ("ó", "o"), ("ú", "u"), ("ů", "u"),
            ("c", "ts"),
            ("j", "y"),
            ("ž", "j"),
            ("ř", "rj"),
            ("č", "ç"), ("š", "ş"),
            ("ě", "ye"), ("ň", "ny"), ("ď", "dy"), ("ť", "ty"),
            ("w", "v"), ("x", "ks")
        ]
        for (from, to) in rules {
            result = result.replacingOccurrences(of: from, with: to)
        }
        return result
    }

